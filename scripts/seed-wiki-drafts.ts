async function main() {
  for (const article of ARTICLES) {
    const existing = await prisma.wikiArticle.findFirst({ where: { title: article.title } });
    if (existing?.published) {
      console.log(`пропущено (уже опубликовано): ${article.title}`);
      continue;
    }
    const base = slugify(article.title);
    const slugTaken = base
      ? await prisma.wikiArticle.findUnique({ where: { slug: base } })
      : null;
    const slug = base && (!slugTaken || slugTaken.id === existing?.id) ? base : null;

    if (existing) {
      await prisma.wikiArticle.update({
        where: { id: existing.id },
        data: { content: article.content, ...(existing.slug ? {} : { slug }) },
      });
      console.log(`обновлён черновик: ${article.title}`);
    } else {
      await prisma.wikiArticle.create({
        data: { title: article.title, content: article.content, published: false, slug },
      });
      console.log(`создан черновик: ${article.title}`);
    }
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
