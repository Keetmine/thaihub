import type { MetadataRoute } from "next";
import { SITE_URL } from "@/lib/seo";

// Каталог открыт для поиска (см. features/auth.md): сериалы, артисты,
// новеллы, локации, агентства и вики индексируются, всё личное и
// служебное — нет. События с недавних пор тоже открыты: карточка
// /event/[id] публична (что, когда, где, кто), а /events показывает
// тизер ближайших — за подпиской остались лента целиком и личные блоки,
// в разметку они не идут. Платные /calendar и /day из индекса выводит
// noindex-мета на самих страницах, а не запрет обхода: закрытое в
// robots.txt Google всё равно показывает по внешним ссылкам
// («indexed, though blocked»), потому что не может дойти до меты.
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: [
          "/admin",
          "/account",
          "/api",
          "/trips",
          // /lists здесь больше нет: публичный список мест открыт гостю
          // по прямой ссылке и должен индексироваться, а один префикс
          // закрывал бы и его. Личное закрыто метой: раздел /lists и
          // непубличные списки отдают noindex (см. lists/[id]/page.tsx),
          // и краулер должен ДОЙТИ до страницы, чтобы её увидеть.
          "/artist-lists",
          "/users",
          "/login",
          "/signup",
          "/welcome",
          "/forgot-password",
          "/reset-password",
          // Выгрузка события в календарь: не страница, а файл .ics, и
          // без подписки маршрут отвечает 403 — краулить нечего.
          // Правило точечное: сам /event/ открыт (см. комментарий выше),
          // а «/event» одним префиксом закрыл бы и его, и /events молча.
          "/event/*/ics",
          // /day здесь больше нет: запрет обхода без noindex давал в
          // Search Console «indexed, though blocked» — адрес попадал в
          // выдачу по внешней ссылке, а мету робот увидеть не мог.
          // Теперь страницы дня отдают noindex сами (day/[date]/page.tsx).
        ],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
  };
}
