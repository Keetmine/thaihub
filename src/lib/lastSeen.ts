import { after } from "next/server";
import { prisma } from "@/lib/prisma";

// Как часто разрешено обновлять User.lastSeenAt.
//
// Отметка нужна ровно для одного вопроса — «человек ещё ходит или
// пропал», с точностью до дня. Писать её на каждый запрос незачем: одна
// открытая страница тянет за собой опрос уведомлений, картинки и
// переходы, и без порога каждый чих стоил бы UPDATE ради поля, которое
// смотрят раз в неделю в админке. Десять минут — компромисс: у активного
// человека максимум 6 записей в час, и при этом «сейчас на сайте»
// (ONLINE_WINDOW_MS) остаётся честным.
export const LAST_SEEN_THROTTLE_MS = 10 * 60 * 1000;

// Окно «сейчас на сайте» для админки. Шире порога записи: иначе человек,
// отметившийся 11 минут назад, выпадал бы из онлайна, хотя следующая
// отметка ему по порогу ещё не положена.
export const ONLINE_WINDOW_MS = 15 * 60 * 1000;

/** Отмечает активность пользователя, если прошлая отметка протухла.
 *  Ничего не ждёт и ничего не роняет: сама запись уходит в `after()`,
 *  то есть уже после отдачи ответа. */
export function touchLastSeen(userId: string, lastSeenAt: Date | null): void {
  if (lastSeenAt && Date.now() - lastSeenAt.getTime() < LAST_SEEN_THROTTLE_MS) return;

  try {
    after(() =>
      prisma.user
        .update({ where: { id: userId }, data: { lastSeenAt: new Date() } })
        // Отметка активности не стоит упавшей страницы: аккаунт могли
        // удалить между рендером и записью, база могла моргнуть.
        .catch(() => {}),
    );
  } catch {
    // after() живёт только внутри запроса. Вне его (скрипты, крон,
    // прогрев сборки) просто не отмечаем — падать тут не за что.
  }
}
