/**
 * Фото в комментариях (АА20 и обсуждения сообществ).
 *
 * Общее место для правил, потому что прикладывают их в двух разных
 * местах — под событием и в теме сообщества, — а правила должны быть
 * одни. Сами файлы уходят в общий `/api/upload`: там уже есть потолки
 * размера (8 МБ), числа файлов за раз и частоты загрузок, то есть
 * защита диска, о которой владелец просила в АА20.
 */

/** Сколько картинок можно приложить к одному комментарию. Три — ровно
 *  столько, сколько ручка загрузки принимает за один раз, и столько же
 *  умещается в ряд под текстом, не превращая ленту в галерею. */
export const COMMENT_PHOTO_LIMIT = 3;

/**
 * Адреса картинок из формы — только НАШИ загрузки.
 *
 * Адрес уходит прямо в `<img src>` на публичной странице, поэтому чужой
 * хост тут был бы дырой: `javascript:`, трекинг-пиксель или картинка,
 * подменённая после модерации. Всё, что не начинается с `/uploads/`,
 * молча выбрасывается — подделать такое поле можно только руками, и
 * объяснять человеку нечего.
 */
export function parseCommentPhotoUrls(values: FormDataEntryValue[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const value of values) {
    const url = String(value).trim();
    if (!url.startsWith("/uploads/") || url.includes("..") || seen.has(url)) continue;
    seen.add(url);
    out.push(url);
    if (out.length >= COMMENT_PHOTO_LIMIT) break;
  }
  return out;
}
