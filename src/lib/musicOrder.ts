/**
 * Порядок музыкальных новинок.
 *
 * Точной даты выхода у нас нет: и страница канала, и страница альбома на
 * YouTube Music отдают только ГОД (проверено 2026-09-15 — полной даты в
 * их HTML нет вовсе). Поэтому «по дате выхода» отсортировать нельзя, и
 * порядок собирается из того, что есть.
 *
 * Ключ, которого раньше не хватало: импорт складывает релизы В ТОМ
 * ПОРЯДКЕ, В КОТОРОМ ИХ ОТДАЛ YOUTUBE MUSIC, а там они идут от новых к
 * старым. То есть внутри одного прогона `createdAt` по возрастанию —
 * это и есть «от свежего к старому». Сортировка `createdAt desc`
 * переворачивала это с ног на голову: у LYKN первым в ленте стоял самый
 * СТАРЫЙ релиз пачки (жалоба владельца 2026-09-15 — «сортируется не по
 * дате выхода»).
 *
 * Отсюда три ключа:
 *   1. год выпуска, убывающе — единственная настоящая дата, что у нас
 *      есть;
 *   2. КОГДА МЫ УЗНАЛИ об этой пачке, убывающе: то, что приехало вчера,
 *      новее того, что лежит с августа;
 *   3. место В ПАЧКЕ, возрастающе — порядок самого YouTube Music.
 *
 * «Пачка» — релизы, заведённые в одну минуту: прогон одного канала
 * занимает секунды (проверено на данных: шесть альбомов LYKN легли за
 * 4,6 секунды).
 */

/** Минимум, по которому строится порядок. */
export type MusicOrderItem = {
  year: number | null;
  /** Когда запись завели у нас. */
  addedAt: Date;
};

/**
 * Ключ пачки — МИНУТА заведения. Артист в ключ не входит: прогон одного
 * канала укладывается в секунды, так что минута его и выделяет, а
 * ночной обход нескольких артистов подряд всё равно идёт от свежего к
 * старому внутри каждого.
 */
function batchKey(item: MusicOrderItem): number {
  return Math.floor(item.addedAt.getTime() / 60_000);
}

/**
 * Сравнение двух релизов для ленты новинок. Сначала год, потом свежесть
 * пачки, потом место внутри пачки.
 */
export function compareMusicNews(a: MusicOrderItem, b: MusicOrderItem): number {
  const byYear = (b.year ?? 0) - (a.year ?? 0);
  if (byYear !== 0) return byYear;
  // Разные пачки — впереди та, что приехала позже.
  const batchA = batchKey(a);
  const batchB = batchKey(b);
  if (batchA !== batchB) return batchB - batchA;
  // Одна пачка (или два одиночных релиза в одну минуту) — порядок
  // вставки, он же порядок YouTube Music: новое сверху.
  return +a.addedAt - +b.addedAt;
}
