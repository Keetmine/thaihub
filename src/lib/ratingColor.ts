/**
 * Цвет оценки — один на весь сайт.
 *
 * Высокая оценка ЖЁЛТАЯ, а не зелёная (правка владельца 2026-09-07):
 * рядом стоят золотые звёзды, и зелёная цифра к ним не клеилась —
 * зелёный на сайте читается как «успешно», а не «хорошо».
 *
 * Пороги кинопоисковые: 7+ — хорошо, 5-6 — серединка (нейтральный
 * серый), ниже — плохо.
 */
export function ratingColor(r: number): string {
  if (r >= 7) return "var(--rating-good)";
  if (r >= 5) return "var(--bs-secondary-color)";
  return "var(--rating-bad)";
}
