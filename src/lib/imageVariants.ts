/**
 * Имена уменьшенных копий картинок — и только они.
 *
 * Отдельный файл, потому что этим пользуются обе стороны: сервер, когда
 * копии делает (`localImage.ts` тянет sharp и fs), и браузер, когда
 * собирает `srcset`. Держи это в localImage — и sharp уехал бы в
 * клиентский бандл вслед за первым же импортом из клиентского
 * компонента. Здесь нет ни одной зависимости, поэтому файл безопасен
 * везде.
 */

/**
 * Ширины уменьшенных копий. Оригиналы у нас 500–900 пикселей по ширине,
 * а показываются в основном мелко: постер в строке афиши — 62
 * CSS-пикселя, карточка каталога — около 160. Двадцать оригиналов на
 * экран списка — это мегабайт с лишним ради картинок размером с ноготь.
 *
 * Две ступени, а не пять: 200 закрывает строки и мелкие карточки, 400 —
 * плитки каталога и экраны с двойной плотностью. Всё, что крупнее,
 * берёт оригинал.
 */
export const SRCSET_WIDTHS = [200, 400] as const;

/**
 * Ширина заглушки для blur-up. Двадцать пикселей — это ~300 байт: файл
 * приходит раньше настоящего постера и, растянутый во всю рамку,
 * читается как размытое пятно нужных цветов. Вместо серой дыры, которая
 * потом дёргается, картинка как будто наводится на резкость.
 *
 * В `srcset` она НЕ попадает: это подложка, а не источник. Иначе
 * браузер имел бы право взять её всерьёз на очень мелком месте.
 */
export const BLUR_WIDTH = 20;

/** Все ширины, которые делаем на диске. */
export const IMAGE_WIDTHS = [BLUR_WIDTH, ...SRCSET_WIDTHS] as const;

/**
 * Ширина, которой мы объявляем оригинал в `srcset`.
 *
 * Настоящей мы не знаем — она не хранится, а читать файл на каждый
 * рендер незачем. Берём верх нашего диапазона: постеры с MDL — 900,
 * с TMDB — 500. Ошибка тут дёшева и всегда в безопасную сторону: под
 * крупное место браузер возьмёт оригинал (так и надо), под мелкое —
 * всё равно копию, потому что 200 и 400 объявлены честно.
 */
const ORIGINAL_WIDTH_HINT = 900;

/** Имя уменьшенной копии: `poster.webp` → `poster-200.webp`. */
export function variantName(filename: string, width: number): string {
  return filename.replace(/\.webp$/, `-${width}.webp`);
}

/** Адрес заглушки для blur-up — или null, если копий у картинки нет. */
export function blurUrl(src: string): string | null {
  if (!src.startsWith("/uploads/") || !src.endsWith(".webp")) return null;
  return variantName(src, BLUR_WIDTH);
}

/** Сама ли это копия? `poster-200.webp` второй раз уменьшать не надо. */
export function isVariantName(name: string): boolean {
  return IMAGE_WIDTHS.some((w) => name.endsWith(`-${w}.webp`));
}

/**
 * `srcset` для картинки из /uploads — или undefined, если копий у неё
 * быть не может (внешний адрес, гифка).
 *
 * Функция ЧИСТАЯ — только от строки адреса, никакого окружения. Это
 * важно, а не просто опрятно: её зовут и серверные, и клиентские
 * компоненты, и обе стороны обязаны получить одно и то же, иначе
 * гидратация снесёт атрибут. На переходный период здесь жил рубильник
 * `IMAGE_VARIANTS_READY` — он не работал ровно поэтому: клиентский
 * бандл видит только NEXT_PUBLIC-переменные, вшитые на сборке, и
 * серверная переменная до него не долетает (а до сервера в docker её
 * не пропускал белый список environment в compose). Копии теперь
 * пишутся вместе с каждой картинкой, догоняющий прогон по старым
 * прошёл — рубильник больше не нужен.
 */
export function uploadSrcSet(src: string): string | undefined {
  if (!src.startsWith("/uploads/") || !src.endsWith(".webp")) return undefined;
  return [
    ...SRCSET_WIDTHS.map((w) => `${variantName(src, w)} ${w}w`),
    `${src} ${ORIGINAL_WIDTH_HINT}w`,
  ].join(", ");
}
