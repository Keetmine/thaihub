/**
 * Адрес загруженной картинки, годный для записи в базу (пустой —
 * «картинку убрали», это законно).
 *
 * Принимаем только собственные `/uploads/…`: адрес уходит прямо в
 * `<img src>` на публичных страницах, и чужой домен в нём — это и
 * утечка реферера каждому, кто открыл страницу, и картинка, которая в
 * любой момент станет чем угодно. `..` отдельно: без этого
 * `/uploads/../../etc` прошёл бы проверку префикса.
 *
 * Правило общее для всех пользовательских картинок (фото профиля, фото
 * своего места). `parseCommunityCoverUrl` в src/lib/communities.ts —
 * более ранняя копия того же правила: подлежит сведению сюда при
 * ближайшей правке того файла.
 */
export function parseUploadUrl(
  raw: unknown,
): { ok: true; url: string | null } | { ok: false } {
  const next = String(raw ?? "").trim() || null;
  if (next && (!next.startsWith("/uploads/") || next.includes(".."))) return { ok: false };
  return { ok: true, url: next };
}
