import { prisma } from "@/lib/prisma";

/** Системный список «Хочу посетить» — куда падают места по кнопке
 *  «Хочу сюда» со страницы локации.
 *
 *  Признак системности — СОГЛАШЕНИЕ по названию, а не поле в базе:
 *  миграции здесь запрещены, поэтому системный список — это обычный
 *  личный `PlaceList` с фиксированным title. Название нарочно одно на
 *  обе локали (не из словаря): возьми мы перевод по текущей локали,
 *  человек, переключивший язык, получил бы ВТОРОЙ «системный» список —
 *  а находить его нужно всегда одинаково.
 *
 *  Известные ограничения v1 (осознанные, см. docs/features/place-lists.md):
 *  - переименование списка на его странице отвязывает кнопку — она
 *    заведёт новый список с тем же названием;
 *  - у пользователя со СВОИМ списком «Хочу посетить» кнопка будет
 *    писать в него (для v1 это даже логично).
 */
export const WANT_TO_VISIT_TITLE = "Хочу посетить";

/** Ищем системный список пользователя. orderBy — на случай дубля (в
 *  теории кнопку можно нажать дважды параллельно): всегда берём самый
 *  старый, чтобы отметки не расползались по двум спискам. */
export function findWantToVisitList(userId: string) {
  return prisma.placeList.findFirst({
    where: { userId, communityId: null, title: WANT_TO_VISIT_TITLE },
    orderBy: { createdAt: "asc" },
  });
}
