import assert from "node:assert/strict";
import { isDue } from "../../src/lib/scheduledJobs";

// isDue планировщика (src/lib/scheduledJobs.ts): суточное поведение
// (intervalDays по умолчанию 1) не изменилось, недельный интервал
// (intervalDays: 7 у задачи "gmmtv-mascots") отсчитывается от последнего
// прогона по календарным дням. Чистая функция — без сети и БД. Запуск:
//
//   npx tsx tests/unit/scheduledJobsDue.test.ts

const at = (iso: string) => new Date(iso);

// --- суточный дефолт: поведение как до недельного интервала ---

assert.equal(isDue(4, null, at("2026-09-05T03:00:00")), false, "час ещё не наступил");
assert.equal(isDue(4, null, at("2026-09-05T04:00:00")), true, "ни разу не запускалась");
assert.equal(
  isDue(4, at("2026-09-05T04:01:00"), at("2026-09-05T23:59:00")),
  false,
  "сегодня уже запускалась",
);
assert.equal(
  isDue(4, at("2026-09-04T04:01:00"), at("2026-09-05T04:00:00")),
  true,
  "вчера запускалась — сегодня пора",
);

// --- недельный интервал (gmmtv-mascots) ---

assert.equal(
  isDue(4, at("2026-09-01T04:00:00"), at("2026-09-05T05:00:00"), 7),
  false,
  "прошло 4 дня из 7 — рано",
);
assert.equal(
  isDue(4, at("2026-08-29T04:00:00"), at("2026-09-05T04:00:00"), 7),
  true,
  "ровно 7 календарных дней — пора",
);
assert.equal(
  isDue(4, at("2026-08-20T04:00:00"), at("2026-09-05T04:00:00"), 7),
  true,
  "больше недели (задача была выключена) — пора",
);
assert.equal(
  isDue(4, at("2026-08-29T04:00:00"), at("2026-09-05T03:00:00"), 7),
  false,
  "неделя прошла, но час прогона ещё не наступил",
);
assert.equal(isDue(4, null, at("2026-09-05T04:00:00"), 7), true, "первый прогон — сразу");

// Разница считается по календарным дням, а не по 168 часам: прогон в
// 04:59 не сдвигает следующий на «через неделю и почти час».
assert.equal(
  isDue(4, at("2026-08-29T04:59:00"), at("2026-09-05T04:00:00"), 7),
  true,
  "время суток последнего прогона не сдвигает день следующего",
);

// --- жёсткий день недели (weekly-digest: воскресенье) ---

// 2026-09-06 — воскресенье, 2026-09-07 — понедельник (проверено
// календарём: см. комментарий к isDue про зону процесса).
assert.equal(
  isDue(10, null, at("2026-09-06T10:00:00"), 7, 0),
  true,
  "воскресенье, час настал, ни разу не запускались",
);
assert.equal(
  isDue(10, null, at("2026-09-07T10:00:00"), 7, 0),
  false,
  "понедельник — не день рассылки, сколько бы ни ждали",
);
assert.equal(
  isDue(10, null, at("2026-09-06T09:00:00"), 7, 0),
  false,
  "воскресенье, но час ещё не наступил",
);
assert.equal(
  isDue(10, at("2026-09-06T10:00:00"), at("2026-09-06T23:00:00"), 7, 0),
  false,
  "сегодня уже рассылали",
);
assert.equal(
  isDue(10, at("2026-09-06T10:00:00"), at("2026-09-13T10:00:00"), 7, 0),
  true,
  "следующее воскресенье — пора",
);
// Пропущенное воскресенье (сервер лежал, задачу выключали) не сдвигает
// рассылку на будни: она просто ждёт следующего воскресенья.
assert.equal(
  isDue(10, at("2026-08-30T10:00:00"), at("2026-09-09T10:00:00"), 7, 0),
  false,
  "прошло больше недели, но сегодня среда",
);
assert.equal(
  isDue(10, at("2026-08-30T10:00:00"), at("2026-09-13T10:00:00"), 7, 0),
  true,
  "пропущенное воскресенье наверстывается в следующее",
);

console.log("scheduledJobsDue.test.ts: ok");
