-- Вид ссылки артиста. Соцсети отдельным видом не выделяем: их узнают по
-- адресу, а вид нужен там, где по адресу не догадаться, — у личных
-- брендов (марка одежды, кафе), которые показываются под описанием
-- своим именем, а не иконкой.
CREATE TYPE "PerformerLinkKind" AS ENUM ('OTHER', 'BRAND');

-- Существующие ссылки остаются прочими: default покрывает все строки,
-- бэкфилл не нужен.
ALTER TABLE "PerformerLink"
  ADD COLUMN "kind" "PerformerLinkKind" NOT NULL DEFAULT 'OTHER';
