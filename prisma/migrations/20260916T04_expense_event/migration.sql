-- Трату можно привязать к СОБЫТИЮ АФИШИ (правка владельца 2026-09-16:
-- «есть евенты, например какой-то фестиваль — многие платные, было б
-- прикольно указывать ценник»).
--
-- Почему привязка, а не просто текст руками: поездка уже знает, что вы
-- идёте на этот фестиваль в такой-то день. Название, набранное руками,
-- живёт отдельно от события — с опечаткой, без даты и без связи.
--
-- Почему НЕ поле цены у самого события (как у брони): событие афиши
-- общее для всех, у каждого свой билет и своя цена. Личная сумма может
-- жить только в личной записи.
--
-- Ссылаемся на EventOccurrence, а не на Event: у фестиваля несколько
-- дней, и «Scream Fest 19 сентября» — это конкретная дата, а не вообще.
-- SetNull: убрали дату из афиши — трата осталась, деньги потрачены.
ALTER TABLE "TripExpense" ADD COLUMN "occurrenceId" TEXT;
CREATE INDEX "TripExpense_occurrenceId_idx" ON "TripExpense"("occurrenceId");
ALTER TABLE "TripExpense" ADD CONSTRAINT "TripExpense_occurrenceId_fkey"
  FOREIGN KEY ("occurrenceId") REFERENCES "EventOccurrence"("id") ON DELETE SET NULL ON UPDATE CASCADE;
