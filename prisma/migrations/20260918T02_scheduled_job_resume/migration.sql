-- Продолжение прогона пачками (правка владельца 2026-09-18: «если в
-- планировщике 600 сериалов, запускать первый прогон, потом через
-- таймер следующий, и так пока не будут спарсены все»).
--
-- Раньше задача была строго суточной: обошла свои 300 карточек из 626 —
-- и до завтра. Остаток ждал следующей ночи, а если прогон обрывался
-- (деплой перезапустил приложение), то и вовсе сутки: отметка о запуске
-- на сегодня уже стояла. Так каталог отставал неделями.
--
-- resumeAt — «этой задаче есть что доделать, продолжи в это время».
-- Планировщик тикает каждые 10 минут; увидев наступивший resumeAt, он
-- запускает задачу ВНЕ суточного правила и берёт следующую пачку.
-- Пусто — обычное поведение «раз в сутки в свой час».
ALTER TABLE "ScheduledJob" ADD COLUMN "resumeAt" TIMESTAMP(3);

-- Задачи, зависшие в RUNNING от прерванного прогона, продолжатся сами:
-- без этого они ждали бы завтрашнего дня (ровно случай 18 сентября —
-- обновление MDL оборвалось на деплое и встало на неделю).
UPDATE "ScheduledJob"
SET "resumeAt" = NOW(), "lastStatus" = 'FAILED',
    "lastSummary" = COALESCE("lastSummary", '') || ' · прерван перезапуском, продолжим'
WHERE "lastStatus" = 'RUNNING';
