-- Тип записи по умолчанию — «Drama» (решение владельца 2026-09-16).
--
-- У двух третей каталога (3387 из 5249 на момент миграции) тип был
-- пуст: записи заведены не с MyDramaList (TMDB, blscene, руками), а
-- там типа нет. Пока каталог показывал всё подряд, это никому не
-- мешало; переключатель «Сериалы / Фильмы / Шоу» на /dramas без типа
-- терял бы две трети сериалов. Правило то же, что уже применялось в
-- seenLive.ts: запись без типа — сериал. Фильмы и шоу у импорта
-- размечены явно, так что чужого в «Сериалы» не попадёт.
UPDATE "Drama" SET "type" = 'Drama' WHERE "type" IS NULL;

-- И дальше новые записи без типа получают «Drama» сами: TMDB заводит
-- только сериалы (media_type = tv), а импорт MDL подставляет тип с
-- карточки тайтла. Колонка остаётся nullable — явный NULL по-прежнему
-- можно записать, но ни один импорт этого больше не делает.
ALTER TABLE "Drama" ALTER COLUMN "type" SET DEFAULT 'Drama';
