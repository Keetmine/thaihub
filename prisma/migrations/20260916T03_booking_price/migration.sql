-- Цена прямо в брони и в личном событии поездки (правка владельца
-- 2026-09-16: «добавить поле цены в самолёты, брони отелей, евенты — и
-- если внесены, выносить их на страницу расходов»).
--
-- Почему поле ЗДЕСЬ, а не отдельной тратой на каждую бронь: перелёт уже
-- заведён, и просить завести его второй раз в другой вкладке — ровно та
-- работа, которую человек не станет делать. Цена живёт там, где её
-- узнают, а вкладка расходов её подхватывает.
--
-- Автосоздания TripExpense при заполнении цены НЕТ намеренно: две
-- записи об одних деньгах пришлось бы держать в синхроне (поправил
-- бронь — поправь копию), и однажды они бы разъехались. Вкладка
-- расходов СЧИТЫВАЕТ цену из брони, а не копирует её.
--
-- Сумма — в минорных единицах, как у TripExpense (см. lib/tripMoney.ts).
-- Валюта своя у каждой записи: перелёт часто в рублях, отель в батах.
